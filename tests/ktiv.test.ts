import { describe, expect, it } from 'vitest';
import { ktivMale } from '../src/lib/ktiv';

describe('ktivMale', () => {
  const cases: [string, string][] = [
    ['שֻׁלְחָן', 'שולחן'], ['סִפּוּר', 'סיפור'], ['תַּלְמִיד', 'תלמיד'], ['מִכְתָּב', 'מכתב'],
    ['שָׁלוֹם', 'שלום'], ['חֹדֶשׁ', 'חודש'], ['דִּבֵּר', 'דיבר'], ['יֶלֶד', 'ילד'], ['לֹא', 'לא'],
    ['תִּקְוָה', 'תקווה'], ['מִצְוָה', 'מצווה'], ['שָׁמַיִם', 'שמיים'], ['צָהֳרַיִם', 'צהריים'],
    ['עִיר', 'עיר'], ['יִשְׂרָאֵל', 'ישראל'], ['כֹּל', 'כל'], ['פֹּה', 'פה'], ['מְדִינָה', 'מדינה'],
    ['אִשָּׁה', 'אישה'], ['שֹׁמֵר', 'שומר'], ['גָּדוֹל', 'גדול'], ['ספר', 'ספר'], ['כִּסֵּא', 'כיסא'],
    ['חֻמּוּס', 'חומוס'], ['אֹכֶל', 'אוכל'], ['בֹּקֶר טוֹב', 'בוקר טוב'], ['עִם', 'עם'],
  ];
  it.each(cases)('%s → %s', (a, b) => expect(ktivMale(a)).toBe(b));
});
