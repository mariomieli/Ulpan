import { describe, expect, it } from 'vitest';
import { syllabify } from '../src/lib/syllables';

describe('syllabify', () => {
  const cases: [string, string][] = [
    ['שָׁלוֹם', 'שָׁ·לוֹם'], ['אַבָּא', 'אַ·בָּא'], ['תַּלְמִיד', 'תַּלְ·מִיד'], ['בְּרָכָה', 'בְּרָ·כָה'],
    ['יְלָדִים', 'יְלָ·דִים'], ['סוּס', 'סוּס'], ['רוּחַ', 'רוּחַ'], ['אֲנִי', 'אֲ·נִי'], ['מֶלֶךְ', 'מֶ·לֶךְ'],
    ['דָּג', 'דָּג'], ['תּוֹדָה רַבָּה', 'תּוֹ·דָה רַ·בָּה'], ['יְרוּשָׁלַיִם', 'יְרוּ·שָׁ·לַ·יִם'],
  ];
  it.each(cases)('%s → %s', (a, b) => expect(syllabify(a)).toBe(b));
});
